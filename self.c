#include <stdio.h>
int main(void) {
    int h, w;
    // Читаем высоту и ширину. Проверяем, что успешно считано ровно 2 числа.
    if (scanf("%d %d", &h, &w) != 2) {
        printf("Input error\n");
        return 0;
    }
    // Проверяем допустимые размеры (от 2 до 10 включительно)
    if (h < 2 || h > 10 || w < 2 || w > 10) {
        printf("Range error\n");
        return 0;
    }
    // Внешний цикл по строкам (от 1 до h)
    for (int row = 1; row <= h; row++) {
        // Внутренний цикл по столбцам (от 1 до w)
        for (int col = 1; col <= w; col++) {
            // Проверяем, является ли текущая позиция границей
            if (row == 1 || row == h || col == 1 || col == w) {
                printf("*");
            } else {
                printf(" ");
            }
        }
        // После завершения внутреннего цикла (конца строки) делаем перевод строки
        printf("\n");
    }
    return 0;
}
